"""Incident report / postmortem generator (Markdown). Structure is deterministic; the
local LLM writes the executive summary and lessons learned (template fallback)."""
from datetime import datetime, timezone

from privacy_layer import read_log

from . import llm
from .agents import fmt_t

REPORT_SCHEMA = {
    "type": "object",
    "properties": {"executive_summary": {"type": "string"},
                   "lessons_learned": {"type": "array", "items": {"type": "string"}},
                   "follow_ups": {"type": "array", "items": {"type": "string"}}},
    "required": ["executive_summary", "lessons_learned", "follow_ups"],
}


def _fmt_dt(t):
    return t.strftime("%Y-%m-%d %H:%M:%S UTC") if isinstance(t, datetime) else str(t)


def build_report(inv, executions, approvals, model):
    tri, la, rca = inv["triage"], inv["logs"], inv["rca"]
    top = rca["hypotheses"][0]
    final = next((e for e in reversed(executions) if e["verification"]["passed"]), None)
    hits = inv["history"]["hits"]
    deploy = inv["deploys"][0] if inv["deploys"] else None

    sys = ("You are the Postmortem agent. Write a blameless postmortem. executive_summary: 4 sentences, plain "
           "English, include impact, root cause, fix, and verification. lessons_learned: 3 bullets. follow_ups: 4 "
           "concrete preventive engineering tasks (alerts, CI checks, runbooks), informed by the past incident fixes.")
    facts = [f"Service: {tri['affected_service']}, severity {tri['severity']}",
             f"Onset: {_fmt_dt(la.get('onset'))}; peak error rate {la.get('peak_error_rate', 0):.0%}",
             f"Root cause: {top['statement']}", "Evidence: " + "; ".join(top["evidence"]),
             f"Blast radius: {', '.join(inv['deps']['blast_radius'])}",
             *[f"Attempt {i + 1}: {e['action']['title']} -> " + ("FIXED the incident (recovery verified by health checks)"
               if e["verification"]["passed"] else "did NOT fix it (errors persisted)") for i, e in enumerate(executions)]]
    facts += [f"Past incident {h['id']}: fix was: {h['fix']}" for h in hits[:2]]
    out, meta = llm.chat_json(sys, "\n".join(facts), REPORT_SCHEMA, model, temperature=0.2)
    if not out:
        out = {"executive_summary": f"{tri['affected_service']} returned errors (peak {la.get('peak_error_rate', 0):.0%}) "
                                    f"starting {_fmt_dt(la.get('onset'))}. {top['statement']} "
                                    + (f"The approved action “{final['action']['title']}” restored service, verified by health checks."
                                       if final else "Recovery has not been verified yet."),
               "lessons_learned": ["Capacity-related config changes need review and load testing.",
                                   "Pool wait time should alert before customers see errors.",
                                   "Deploy correlation shortened diagnosis."],
               "follow_ups": ["Alert on DB pool wait time and saturation.",
                              "CI check that flags capacity config changes > 50%.",
                              "Add canary analysis to deploy pipeline.",
                              "Runbook: pool exhaustion triage and rollback."]}

    now = datetime.now(timezone.utc)
    timeline = []
    if deploy:
        timeline.append((deploy["timestamp"].replace("T", " ").replace("Z", " UTC"),
                         f"Deploy {deploy['service']} {deploy['version']} by {deploy['author']}: {deploy['summary']}"))
    if la.get("onset"):
        timeline.append((_fmt_dt(la["onset"]), f"First errors: {la['signatures'][0]['signature'] if la['signatures'] else ''}"))
    timeline.append((_fmt_dt(inv["started_at"]), f"Incident reported by voice/text; {len(inv['trace'])} agent steps, "
                                                 f"investigation took {inv['elapsed_s']:.0f} s"))
    for a in approvals:
        timeline.append((_fmt_dt(a["at"]), f"{a['decision'].upper()} by {a['approver']}: {a['action_title']}"))
    for e in executions:
        timeline.append((_fmt_dt(e["at"]), f"Executed (simulated): {e['action']['title']} → "
                                           f"{'recovery verified' if e['verification']['passed'] else 'recovery NOT verified'}"))

    timeline.sort(key=lambda r: r[0])
    egress = read_log()
    sent = [r for r in egress if not r.get("blocked")]
    blocked = [r for r in egress if r.get("blocked")]

    kind = tri["category"].replace("_", " ") if tri["category"] != "other" else "incident"
    md = [f"# Incident report: {tri['affected_service']} {kind} ({tri['severity']})",
          "", f"*Generated by IncidentVoice on {_fmt_dt(now)} · model `{model}` (local) · status: "
              f"**{'RESOLVED (verified)' if final else 'MITIGATION PENDING'}***", "",
          "## Executive summary", out["executive_summary"], "",
          "## Impact",
          f"- **Affected service:** {tri['affected_service']}; **blast radius:** {', '.join(inv['deps']['blast_radius'])}",
          f"- **Peak error rate:** {la.get('peak_error_rate', 0):.0%} (5-min buckets); error rate since onset "
          f"{la.get('error_rate_after_onset', 0):.0%}",
          f"- **Latency:** median {la.get('latency_before_ms')} ms before → {la.get('latency_after_ms')} ms after onset",
          f"- **Symptoms reported:** {', '.join(tri['symptoms'])}", "",
          "## Timeline (UTC)", "| Time | Event |", "|---|---|", *[f"| {t} | {e} |" for t, e in timeline], "",
          "## Root cause", f"**{top['statement']}** (confidence {top['confidence']:.0%})", "",
          top.get("explanation", ""), "", "**Evidence**", *[f"- {e}" for e in top["evidence"]], "",
          "**Other hypotheses considered**",
          *[f"- {h['id']} ({h['confidence']:.0%}): {h['statement']}" for h in rca["hypotheses"][1:4]], "",
          "## Similar past incidents (RAG)",
          *[f"- **{h['id']}** {h['title']} (BM25 {h['score']:.1f}). Fix then: {h['fix']}" for h in hits], "",
          "## Remediation and verification"]
    for e in executions:
        v = e["verification"]
        md += [f"### {e['action']['title']} ({'✅ verified' if v['passed'] else '❌ not verified'})",
               f"Approved by **{e['approver']}** · risk {e['action']['risk']} · simulated environment", "",
               "```", *e["log"], "```", f"Criteria: {v['criteria']}", "",
               "| Check | Error rate | p99 (ms) | Pool waiting | Status |", "|---|---|---|---|---|",
               *[f"| {fmt_t(s['t'])} | {s['error_rate']:.1%} | {s['p99_ms']} | {s['pool_waiting']} | {s['status']} |"
                 for s in e["samples"]], ""]
    md += ["## Lessons learned", *[f"- {x}" for x in out["lessons_learned"]], "",
           "## Follow-up actions", *[f"- [ ] {x}" for x in out["follow_ups"]], "",
           "## Privacy statement",
           f"- Logs were scrubbed on load ({sum(inv['scrubbed'].values())} sensitive values replaced: "
           + ", ".join(f"{k} {v}" for k, v in inv["scrubbed"].items() if v) + ").",
           f"- All reasoning ran on a local open-source model (`{model}` via Ollama). No log data left the machine.",
           f"- Egress audit log: {len(sent)} outbound requests (speech-to-text audio only), {len(blocked)} blocked by the leak gate."]
    return "\n".join(md), meta
